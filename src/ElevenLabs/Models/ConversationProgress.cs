[Serializable]
public record ConversationProgress : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <value>Calls due to be placed that haven't started.</value>
    [JsonPropertyName("scheduled")]
    public required int Scheduled { get; set; }

    /// <value>Scheduled calls by call type. Missing keys mean none.</value>
    [JsonPropertyName("scheduled_by_type")]
    public Dictionary<string, int> ScheduledByType { get; set; } = new Dictionary<string, int>();

    /// <value>WhatsApp calls waiting on the contact to grant call permission.</value>
    [JsonPropertyName("awaiting_permission")]
    public required int AwaitingPermission { get; set; }

    /// <value>Calls under way.</value>
    [JsonPropertyName("in_progress")]
    public required int InProgress { get; set; }

    /// <value>Ended calls whose analysis the campaign is waiting on.</value>
    [JsonPropertyName("awaiting_analysis")]
    public required int AwaitingAnalysis { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    /// <remarks>
    /// Written out rather than synthesized. A record's generated Equals compares every instance
    /// field, and `_extensionData` is a fresh Dictionary per instance compared by REFERENCE, so two
    /// identical models were never equal — silently defeating ==, Distinct(), HashSet membership,
    /// dictionary keys and test assertions for every model in the SDK. Excluding it loses nothing:
    /// it is a transient deserialization sink whose contents are copied into
    /// AdditionalProperties, which IS compared here.
    /// </remarks>
    public virtual bool Equals(ConversationProgress? other)
    {
        if (other is null)
        {
            return false;
        }
        if (ReferenceEquals(this, other))
        {
            return true;
        }
        // The synthesized record Equals compares EqualityContract, so a base instance never equals a
        // derived one. Hand-writing Equals drops that unless it is restated.
        if (EqualityContract != other.EqualityContract)
        {
            return false;
        }
        // Declared properties first: the additional-properties comparison walks a dictionary and
        // allocates a string per entry, and is the least likely of the three to differ, so letting
        // the cheap scalar comparisons short-circuit ahead of it matters for Distinct/HashSet over
        // large collections. Anchored on `true` so a model with no declared properties still emits
        // a valid expression.
        return true
            && ValueEquality.AreEqual(Scheduled, other.Scheduled)
            && ValueEquality.AreEqual(ScheduledByType, other.ScheduledByType)
            && ValueEquality.AreEqual(AwaitingPermission, other.AwaitingPermission)
            && ValueEquality.AreEqual(InProgress, other.InProgress)
            && ValueEquality.AreEqual(AwaitingAnalysis, other.AwaitingAnalysis)
            && AdditionalProperties.Equals(other.AdditionalProperties);
    }

    /// <inheritdoc />
    public override int GetHashCode()
    {
        unchecked
        {
            var hash = 17;
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(Scheduled);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(ScheduledByType);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(AwaitingPermission);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(InProgress);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(AwaitingAnalysis);
            hash = (hash * 31) + AdditionalProperties.GetHashCode();
            return hash;
        }
    }

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
