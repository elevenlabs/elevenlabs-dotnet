/// <summary>Derived approval state for a currently discovered MCP tool.</summary>
[Serializable]
public record McpToolApprovalStatus : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <value>Canonical MCP tool identifier in the form mcp:&lt;server_id&gt;:&lt;tool_name&gt;</value>
    [JsonPropertyName("tool_id")]
    public required string ToolId { get; set; }

    /// <value>Whether a discovered MCP tool has an approval and whether it still matches.</value>
    [JsonPropertyName("state")]
    public required McpToolApprovalState State { get; set; }

    /// <value>Stored execution policy. Set when the tool has an approval.</value>
    [JsonPropertyName("approval_policy")]
    public McpToolApprovalPolicy? ApprovalPolicy { get; set; }

    /// <value>Previously approved definition, included when the tool needs review and a snapshot exists.</value>
    [JsonPropertyName("approved_definition")]
    public McpApprovedToolDefinition? ApprovedDefinition { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    /// <remarks>
    /// Written out rather than synthesized. A record's generated Equals compares every instance
    /// field, and `_extensionData` is a fresh Dictionary per instance compared by REFERENCE, so two
    /// identical models were never equal — silently defeating ==, Distinct(), HashSet membership,
    /// dictionary keys and test assertions for every model in the SDK. Excluding it loses nothing:
    /// it is a transient deserialization sink whose contents are copied into
    /// AdditionalProperties, which IS compared here.
    /// </remarks>
    public virtual bool Equals(McpToolApprovalStatus? other)
    {
        if (other is null)
        {
            return false;
        }
        if (ReferenceEquals(this, other))
        {
            return true;
        }
        // The synthesized record Equals compares EqualityContract, so a base instance never equals a
        // derived one. Hand-writing Equals drops that unless it is restated.
        if (EqualityContract != other.EqualityContract)
        {
            return false;
        }
        // Declared properties first: the additional-properties comparison walks a dictionary and
        // allocates a string per entry, and is the least likely of the three to differ, so letting
        // the cheap scalar comparisons short-circuit ahead of it matters for Distinct/HashSet over
        // large collections. Anchored on `true` so a model with no declared properties still emits
        // a valid expression.
        return true
            && ValueEquality.AreEqual(ToolId, other.ToolId)
            && ValueEquality.AreEqual(State, other.State)
            && ValueEquality.AreEqual(ApprovalPolicy, other.ApprovalPolicy)
            && ValueEquality.AreEqual(ApprovedDefinition, other.ApprovedDefinition)
            && AdditionalProperties.Equals(other.AdditionalProperties);
    }

    /// <inheritdoc />
    public override int GetHashCode()
    {
        unchecked
        {
            var hash = 17;
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(ToolId);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(State);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(ApprovalPolicy);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(ApprovedDefinition);
            hash = (hash * 31) + AdditionalProperties.GetHashCode();
            return hash;
        }
    }

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
