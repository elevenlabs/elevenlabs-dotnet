/// <summary>
/// The agent's data collection items that steer follow-up calls. Each defaults
/// to the built-in item for its purpose; `null` turns it off.
/// </summary>
[Serializable]
public record DataCollectionConfig : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <value>The item holding when the contact asked to be called back.</value>
    [JsonPropertyName("callback_time")]
    public string? CallbackTime { get; set; }

    /// <value>The item holding another number the contact asked to be called on.</value>
    [JsonPropertyName("redirect_phone_number")]
    public string? RedirectPhoneNumber { get; set; }

    /// <value>The item that is true when the contact asked not to be called again.</value>
    [JsonPropertyName("stop")]
    public string? Stop { get; set; }

    /// <value>Copies data collection results into dynamic variables for later calls: each key is a data collection item ID and its value the variable's name.</value>
    [JsonPropertyName("mappings")]
    public Dictionary<string, string>? Mappings { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    /// <remarks>
    /// Written out rather than synthesized. A record's generated Equals compares every instance
    /// field, and `_extensionData` is a fresh Dictionary per instance compared by REFERENCE, so two
    /// identical models were never equal — silently defeating ==, Distinct(), HashSet membership,
    /// dictionary keys and test assertions for every model in the SDK. Excluding it loses nothing:
    /// it is a transient deserialization sink whose contents are copied into
    /// AdditionalProperties, which IS compared here.
    /// </remarks>
    public virtual bool Equals(DataCollectionConfig? other)
    {
        if (other is null)
        {
            return false;
        }
        if (ReferenceEquals(this, other))
        {
            return true;
        }
        // The synthesized record Equals compares EqualityContract, so a base instance never equals a
        // derived one. Hand-writing Equals drops that unless it is restated.
        if (EqualityContract != other.EqualityContract)
        {
            return false;
        }
        // Declared properties first: the additional-properties comparison walks a dictionary and
        // allocates a string per entry, and is the least likely of the three to differ, so letting
        // the cheap scalar comparisons short-circuit ahead of it matters for Distinct/HashSet over
        // large collections. Anchored on `true` so a model with no declared properties still emits
        // a valid expression.
        return true
            && ValueEquality.AreEqual(CallbackTime, other.CallbackTime)
            && ValueEquality.AreEqual(RedirectPhoneNumber, other.RedirectPhoneNumber)
            && ValueEquality.AreEqual(Stop, other.Stop)
            && ValueEquality.AreEqual(Mappings, other.Mappings)
            && AdditionalProperties.Equals(other.AdditionalProperties);
    }

    /// <inheritdoc />
    public override int GetHashCode()
    {
        unchecked
        {
            var hash = 17;
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(CallbackTime);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(RedirectPhoneNumber);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(Stop);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(Mappings);
            hash = (hash * 31) + AdditionalProperties.GetHashCode();
            return hash;
        }
    }

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
