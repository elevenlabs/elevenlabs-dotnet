/// <summary>One segment of a target transcript: a source segment plus its translation.</summary>
[Serializable]
public record DubbingTargetTranscriptSegment : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <value>Stable identifier of the segment (from the source).</value>
    [JsonPropertyName("id")]
    public required string Id { get; set; }

    /// <value>Identifier of the segment's speaker.</value>
    [JsonPropertyName("speaker_id")]
    public required string SpeakerId { get; set; }

    /// <value>Start time of the segment, in seconds.</value>
    [JsonPropertyName("start_s")]
    public required double StartS { get; set; }

    /// <value>End time of the segment, in seconds.</value>
    [JsonPropertyName("end_s")]
    public required double EndS { get; set; }

    /// <value>The source-language text of the segment.</value>
    [JsonPropertyName("source_text")]
    public required string SourceText { get; set; }

    /// <value>The translated text, or null if not translated yet (needs translation).</value>
    [JsonPropertyName("translation")]
    public string? Translation { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    /// <remarks>
    /// Written out rather than synthesized. A record's generated Equals compares every instance
    /// field, and `_extensionData` is a fresh Dictionary per instance compared by REFERENCE, so two
    /// identical models were never equal — silently defeating ==, Distinct(), HashSet membership,
    /// dictionary keys and test assertions for every model in the SDK. Excluding it loses nothing:
    /// it is a transient deserialization sink whose contents are copied into
    /// AdditionalProperties, which IS compared here.
    /// </remarks>
    public virtual bool Equals(DubbingTargetTranscriptSegment? other)
    {
        if (other is null)
        {
            return false;
        }
        if (ReferenceEquals(this, other))
        {
            return true;
        }
        // The synthesized record Equals compares EqualityContract, so a base instance never equals a
        // derived one. Hand-writing Equals drops that unless it is restated.
        if (EqualityContract != other.EqualityContract)
        {
            return false;
        }
        // Declared properties first: the additional-properties comparison walks a dictionary and
        // allocates a string per entry, and is the least likely of the three to differ, so letting
        // the cheap scalar comparisons short-circuit ahead of it matters for Distinct/HashSet over
        // large collections. Anchored on `true` so a model with no declared properties still emits
        // a valid expression.
        return true
            && ValueEquality.AreEqual(Id, other.Id)
            && ValueEquality.AreEqual(SpeakerId, other.SpeakerId)
            && ValueEquality.AreEqual(StartS, other.StartS)
            && ValueEquality.AreEqual(EndS, other.EndS)
            && ValueEquality.AreEqual(SourceText, other.SourceText)
            && ValueEquality.AreEqual(Translation, other.Translation)
            && AdditionalProperties.Equals(other.AdditionalProperties);
    }

    /// <inheritdoc />
    public override int GetHashCode()
    {
        unchecked
        {
            var hash = 17;
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(Id);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(SpeakerId);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(StartS);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(EndS);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(SourceText);
            hash = (hash * 31) + ValueEquality.GetHashCodeOf(Translation);
            hash = (hash * 31) + AdditionalProperties.GetHashCode();
            return hash;
        }
    }

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
