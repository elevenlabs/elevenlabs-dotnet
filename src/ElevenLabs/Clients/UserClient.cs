/// <summary>
/// Fern-shape client for UserClient. Public surface mirrors Fern; execution delegates to the
/// internal legacy service runtime. Declared <c>partial</c> so the interface base
/// (<c>IUserClient</c>, FSM-144) can be added in a sibling declaration.
/// </summary>
public partial class UserClient
{
    private readonly UserService _service;

    internal UserClient(global::ElevenLabs.Http.Client httpClient)
    {
        _service = new UserService(httpClient);
        Subscription = new SubscriptionClient(httpClient);
    }

    public ISubscriptionClient Subscription { get; }

    /// <summary>
    /// Sets service-level configuration for every method on this client.
    /// Overridden by method-level config and by per-call <c>RequestOptions</c>.
    /// </summary>
    public IUserClient SetConfig(global::ElevenLabs.Config.RequestConfig config)
    {
        _service.SetConfig(config);
        return this;
    }

    /// <summary>
    /// Sets method-level configuration for <c>GetAsync</c>.
    /// Overrides service-level configuration; overridden by per-call <c>RequestOptions</c>.
    /// </summary>
    public IUserClient SetGetAsyncConfig(global::ElevenLabs.Config.RequestConfig config)
    {
        _service.SetGetAsyncConfig(config);
        return this;
    }

    /// <summary>Gets information about the user</summary>
    public WithRawResponseTask<User> GetAsync(
        GetUserRequest request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    ) =>
        new WithRawResponseTask<User>(
            WithRawResponseAdapter.Wrap(
                options,
                () => _service.GetAsync(request.XiApiKey, cancellationToken: cancellationToken)
            )
        );
}
