/// <summary>
/// Fern-shape client for TeamClient. Public surface mirrors Fern; execution delegates to the
/// internal legacy service runtime. Declared <c>partial</c> so the interface base
/// (<c>ITeamClient</c>, FSM-144) can be added in a sibling declaration.
/// </summary>
public partial class TeamClient
{
    internal TeamClient(global::ElevenLabs.Http.Client httpClient)
    {
        Members = new ElevenLabs.Reception.Team.MembersClient(httpClient);
        Invites = new ElevenLabs.Reception.Team.InvitesClient(httpClient);
    }

    public ElevenLabs.Reception.Team.IMembersClient Members { get; }
    public ElevenLabs.Reception.Team.IInvitesClient Invites { get; }
}
